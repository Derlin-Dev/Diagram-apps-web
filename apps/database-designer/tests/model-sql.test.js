test('limita y desambigua nombres de constraints FK para los motores SQL', () => {
  const prefix = 'tabla_' + 'x'.repeat(54);
  const m = model([
    T('source', 'origen', [F('source_id', 'id', 'INT', { pk: true, nn: true })]),
    T('target1', `${prefix}a`, [
      F('target_id1', 'id', 'INT', { pk: true, nn: true }),
      F('fk1', 'origen_id', 'INT', { fk: true }),
    ]),
    T('target2', `${prefix}b`, [
      F('target_id2', 'id', 'INT', { pk: true, nn: true }),
      F('fk2', 'origen_id', 'INT', { fk: true }),
    ]),
  ], [
    { id: 'r1', sourceTable: 'source', sourceField: 'source_id', targetTable: 'target1', targetField: 'fk1' },
    { id: 'r2', sourceTable: 'source', sourceField: 'source_id', targetTable: 'target2', targetField: 'fk2' },
  ]);
  for (const dialect of ['mysql', 'postgres', 'sqlite']) {
    const sql = generateSQL(m, dialect);
    const names = [...sql.matchAll(/CONSTRAINT [`"]([^`"]+)[`"]/g)].map((match) => match[1]);
    assert.equal(names.length, 2);
    assert.ok(names.every((name) => name.length <= 63));
    assert.notEqual(names[0], names[1]);
  }
});

