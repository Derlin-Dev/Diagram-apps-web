test('updateRelation limpia UNIQUE que añadió al cambiar 1:1 a 1:N y actualiza el grupo N:M', () => {
  const m = model([
    T('t1', 'a', [idField('f1')]),
    T('t2', 'b', [idField('f2'), F('f3', 'a_id', 'INT', { fk: true })]),
    T('t3', 'puente', [
      F('f4', 'a_id', 'INT', { pk: true, nn: true, fk: true }),
      F('f5', 'b_id', 'INT', { pk: true, nn: true, fk: true }),
    ], { junction: 'g1' }),
  ], [
    { id: 'r1', type: '1:N', sourceTable: 't1', sourceField: 'f1', targetTable: 't2', targetField: 'f3', onDelete: 'NO ACTION', onUpdate: 'NO ACTION', created: false, uqAdded: false, group: null },
    { id: 'r2', type: '1:N', sourceTable: 't1', sourceField: 'f1', targetTable: 't3', targetField: 'f4', onDelete: 'NO ACTION', onUpdate: 'NO ACTION', created: true, uqAdded: false, group: 'g1' },
    { id: 'r3', type: '1:N', sourceTable: 't2', sourceField: 'f2', targetTable: 't3', targetField: 'f5', onDelete: 'NO ACTION', onUpdate: 'NO ACTION', created: true, uqAdded: false, group: 'g1' },
  ]);
  M.updateRelation(m, 'r1', { type: '1:1' });
  assert.equal(m.tables[1].fields[1].uq, true);
  M.updateRelation(m, 'r1', { type: '1:N' });
  assert.equal(m.tables[1].fields[1].uq, false);
  M.updateRelation(m, 'r2', { onDelete: 'CASCADE', onUpdate: 'RESTRICT' });
  assert.deepEqual(m.relations.slice(1).map((relation) => [relation.onDelete, relation.onUpdate]), [
    ['CASCADE', 'RESTRICT'], ['CASCADE', 'RESTRICT'],
  ]);
  assert.throws(() => M.updateRelation(m, 'r2', { onDelete: 'SET NULL' }), /clave primaria/);
});

