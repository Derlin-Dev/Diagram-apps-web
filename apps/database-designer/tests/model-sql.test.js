const test = require('node:test');
const assert = require('node:assert/strict');
const M = require('../js/model.js');
const { generateSQL } = require('../js/sql.js');

let n = 1000; // evita colisiones con los ids fijos de los fixtures
const makeId = (p) => p + n++;

const F = (id, name, type, o = {}) => ({ id, name, type, pk: false, nn: false, ai: false, uq: false, fk: false, ...o });
const T = (id, name, fields, o = {}) => ({ id, name, x: 0, y: 0, color: '#1684e8', junction: null, fields, ...o });
const idField = (id) => F(id, 'id', 'INT', { pk: true, nn: true, ai: true });
const model = (tables, relations = []) => ({ tables, relations });

test('ordena las tablas por dependencias aunque se hayan creado al revés', () => {
  const m = model([
    T('t2', 'pedidos', [idField('f2'), F('f3', 'cliente_id', 'INT', { nn: true, fk: true })]),
    T('t1', 'clientes', [idField('f1')]),
  ], [{ id: 'r1', type: '1:N', sourceTable: 't1', sourceField: 'f1', targetTable: 't2', targetField: 'f3', onDelete: 'NO ACTION', onUpdate: 'NO ACTION' }]);
  const sql = generateSQL(m, 'mysql');
  assert.ok(sql.indexOf('CREATE TABLE `clientes`') < sql.indexOf('CREATE TABLE `pedidos`'));
  assert.match(sql, /FOREIGN KEY \(`cliente_id`\) REFERENCES `clientes` \(`id`\)/);
  assert.match(sql, /CREATE TABLE `clientes` \([\s\S]*\) ENGINE=InnoDB;/);
});

test('ciclos: en MySQL/PostgreSQL la FK se difiere con ALTER TABLE; en SQLite va inline', () => {
  const m = model([
    T('a', 'a', [idField('a1'), F('a2', 'b_id', 'INT', { fk: true })]),
    T('b', 'b', [idField('b1'), F('b2', 'a_id', 'INT', { fk: true })]),
  ], [
    { id: 'r1', type: '1:N', sourceTable: 'b', sourceField: 'b1', targetTable: 'a', targetField: 'a2', onDelete: 'NO ACTION', onUpdate: 'NO ACTION' },
    { id: 'r2', type: '1:N', sourceTable: 'a', sourceField: 'a1', targetTable: 'b', targetField: 'b2', onDelete: 'NO ACTION', onUpdate: 'NO ACTION' },
  ]);
  assert.match(generateSQL(m, 'postgres'), /ALTER TABLE "a"\n {2}ADD CONSTRAINT/);
  assert.doesNotMatch(generateSQL(m, 'sqlite'), /ALTER TABLE/);
});

