test('createRelation rechaza origen sin PK/UNIQUE y tipos incompatibles, sin modificar el modelo', () => {
  const m = model([
    T('t1', 'a', [idField('f1'), F('f2', 'nombre', 'TEXT')]),
    T('t2', 'b', [idField('f3'), F('f4', 'a_id', 'VARCHAR(255)')]),
  ]);
  assert.throws(() => M.createRelation(m, { type: '1:N', sourceTable: 't1', sourceField: 'f2', targetTable: 't2', fkName: 'x' }, makeId), /PK o UNIQUE/);
  assert.throws(() => M.createRelation(m, { type: '1:N', sourceTable: 't1', sourceField: 'f1', targetTable: 't2', fkName: 'a_id' }, makeId), /debe ser INT/);
  assert.equal(m.relations.length, 0);
  assert.equal(m.tables[1].fields.length, 2);
});

test('N:M crea tabla puente con PK compuesta y dos relaciones; se elimina como grupo', () => {
  const m = model([T('t1', 'productos', [idField('f1')]), T('t2', 'categorias', [idField('f2')])]);
  const res = M.createRelation(m, { type: 'N:M', sourceTable: 't1', sourceField: 'f1', targetTable: 't2', targetField: 'f2', onDelete: 'CASCADE' }, makeId);
  assert.equal(m.tables.length, 3);
  assert.equal(m.relations.length, 2);
  assert.equal(res.table.name, 'productos_categorias');
  assert.deepEqual(res.table.fields.map((f) => f.name), ['producto_id', 'categoria_id']);
  const sql = generateSQL(m, 'mysql');
  assert.match(sql, /PRIMARY KEY \(`producto_id`, `categoria_id`\)/);
  assert.match(sql, /-- Tabla puente/);
  assert.ok(sql.indexOf('CREATE TABLE `productos_categorias`') > sql.indexOf('CREATE TABLE `categorias`'));
  M.dropRelation(m, m.relations[0].id);
  assert.equal(m.tables.length, 2);
  assert.equal(m.relations.length, 0);
});

