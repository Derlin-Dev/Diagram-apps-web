test('removeTable limpia las FK huérfanas de otras tablas y las tablas puente', () => {
  const m = model([T('t1', 'a', [idField('f1')]), T('t2', 'b', [idField('f2')]), T('t3', 'c', [idField('f3')])]);
  M.createRelation(m, { type: '1:N', sourceTable: 't1', sourceField: 'f1', targetTable: 't2', fkName: 'a_id' }, makeId);
  M.createRelation(m, { type: 'N:M', sourceTable: 't2', sourceField: 'f2', targetTable: 't3', targetField: 'f3' }, makeId);
  M.removeTable(m, 't1');
  assert.equal(m.tables.find((t) => t.id === 't2').fields.some((f) => f.name === 'a_id'), false);
  M.removeTable(m, 't3');
  assert.equal(m.tables.length, 1);
  assert.equal(m.relations.length, 0);
});

