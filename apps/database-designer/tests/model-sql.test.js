test('sanea metadatos de campo retrocompatibles y emite valores DEFAULT seguros en cada dialecto', () => {
  const source = model([T('t1', 'eventos', [
    F('f1', 'id', 'INT', { pk: true, nn: true, ai: true }),
    F('f2', 'nombre', 'VARCHAR(255)', { description: 'Nombre del evento', defaultValue: "O'Reilly" }),
    F('f3', 'precio', 'DECIMAL(10,2)', { defaultValue: '12.50' }),
    F('f4', 'activo', 'BOOLEAN', { defaultValue: 'true' }),
    F('f5', 'creado_en', 'DATETIME', { defaultValue: 'CURRENT_TIMESTAMP' }),
  ])]);
  const sanitized = M.sanitizeModel(JSON.parse(JSON.stringify(source)), makeId);
  assert.equal(sanitized.tables[0].fields[1].description, 'Nombre del evento');
  assert.equal(sanitized.tables[0].fields[1].defaultValue, "O'Reilly");
  assert.equal(M.sanitizeModel({ tables: source.tables.map((table) => ({ ...table, fields: table.fields.map(({ description, defaultValue, ...field }) => field) })), relations: [] }, makeId).tables[0].fields[0].defaultValue, null);
  for (const dialect of ['mysql', 'postgres', 'sqlite']) {
    const sql = generateSQL(sanitized, dialect);
    assert.match(sql, /DEFAULT 'O''Reilly'/);
    assert.match(sql, /DEFAULT 12\.50/);
    assert.match(sql, /DEFAULT TRUE/);
    assert.match(sql, /DEFAULT CURRENT_TIMESTAMP/);
  }
  assert.match(generateSQL(sanitized, 'mysql'), /`id` INT PRIMARY KEY AUTO_INCREMENT/);
  assert.match(generateSQL(sanitized, 'sqlite'), /"id" INTEGER PRIMARY KEY AUTOINCREMENT/);
});

