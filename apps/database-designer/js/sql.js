/*
 * sql.js — Generador de SQL puro: generateSQL(model, dialect) → string.
 * Funciona como <script> clásico (window.DBD) y como módulo CommonJS en Node.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.DBD = Object.assign(root.DBD || {}, api);
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const INT_TYPES = ['INT', 'BIGINT'];
  const validateFieldDefault = (field) => {
    if (field.defaultValue === null || field.defaultValue === undefined) return null;
    const value = String(field.defaultValue);
    if (value.length > 256 || /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(value)) return 'invalid';
    if (field.ai) return 'invalid';
    if (INT_TYPES.includes(field.type)) return /^[-+]?\d+$/.test(value) ? null : 'invalid';
    if (field.type.startsWith('DECIMAL')) {
      return /^[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:e[-+]?\d+)?$/i.test(value) ? null : 'invalid';
    }
    if (field.type === 'BOOLEAN') return /^(?:true|false|0|1)$/i.test(value) ? null : 'invalid';
    if (/^CURRENT_TIMESTAMP(?:\(\))?$/i.test(value) && field.type !== 'DATE' && field.type !== 'DATETIME') return 'invalid';
    return null;
  };

  function generateSQL(model, dialect) {
    if (!['mysql', 'postgres', 'sqlite'].includes(dialect)) dialect = 'mysql';
    const { tables, relations } = model;
    if (!tables.length) return '-- Agrega una tabla para generar SQL.\n';

    const q = (n) =>
      dialect === 'mysql' ? '`' + n.replace(/`/g, '``') + '`' : '"' + n.replace(/"/g, '""') + '"';

    const mapType = (t) => {
      if (dialect === 'mysql') return t === 'UUID' ? 'CHAR(36)' : t;
      if (dialect === 'postgres') {
        if (t === 'INT') return 'INTEGER';
        if (t === 'DATETIME') return 'TIMESTAMP';
        return t;
      }
      // sqlite
      if (INT_TYPES.includes(t) || t === 'BOOLEAN') return 'INTEGER';
      if (t.startsWith('DECIMAL')) return 'NUMERIC';
      return 'TEXT'; // VARCHAR, TEXT, DATE, DATETIME, UUID
    };

    const byId = new Map(tables.map((t) => [t.id, t]));
    const findField = (t, id) => t && t.fields.find((f) => f.id === id);

    function columnSQL(f, singlePk) {
      const intLike = INT_TYPES.includes(f.type);
      let s = `  ${q(f.name)} `;
      if (dialect === 'sqlite' && f.pk && singlePk && f.ai && intLike) {
        return s + 'INTEGER PRIMARY KEY AUTOINCREMENT';
      }
      s += mapType(f.type);
      if (dialect === 'postgres' && f.ai && intLike) s += ' GENERATED BY DEFAULT AS IDENTITY';
      if (f.defaultValue !== null && f.defaultValue !== undefined && !validateFieldDefault(f)) {
        const value = String(f.defaultValue);
        let sqlValue;
        if (INT_TYPES.includes(f.type) || f.type.startsWith('DECIMAL') || (f.type === 'BOOLEAN' && /^(?:0|1)$/i.test(value))) {
          sqlValue = value;
        } else if (f.type === 'BOOLEAN') {
          sqlValue = value.toUpperCase();
        } else if ((f.type === 'DATE' || f.type === 'DATETIME') && /^CURRENT_TIMESTAMP(?:\(\))?$/i.test(value)) {
          sqlValue = 'CURRENT_TIMESTAMP';
        } else {
          sqlValue = `'${value.replace(/'/g, "''")}'`;
        }
        s += ` DEFAULT ${sqlValue}`;
      }
      if (f.pk && singlePk) s += ' PRIMARY KEY';
      if (dialect === 'mysql' && f.ai && f.pk && singlePk && intLike) s += ' AUTO_INCREMENT';
      if (!f.pk && f.nn) s += ' NOT NULL';
      if (!f.pk && f.uq) s += ' UNIQUE';
      return s;
    }

    const usedNames = new Set();
    function fkSQL(r) {
      const src = byId.get(r.sourceTable);
      const dst = byId.get(r.targetTable);
      const sf = findField(src, r.sourceField);
      const tf = findField(dst, r.targetField);
      if (!src || !dst || !sf || !tf) return null;
      const base = `fk_${dst.name}_${tf.name}`.replace(/[^A-Za-z0-9_]/g, '_');
      let name = base;
      for (let i = 2; usedNames.has(name.toLowerCase()); i++) name = `${base}_${i}`;
      usedNames.add(name.toLowerCase());
      let out = `CONSTRAINT ${q(name)} FOREIGN KEY (${q(tf.name)}) REFERENCES ${q(src.name)} (${q(sf.name)})`;
      if (r.onDelete && r.onDelete !== 'NO ACTION') out += ` ON DELETE ${r.onDelete}`;
      if (r.onUpdate && r.onUpdate !== 'NO ACTION') out += ` ON UPDATE ${r.onUpdate}`;
      return out;
    }

    // Orden topológico: una tabla se emite después de las que referencia.
    const deps = new Map(tables.map((t) => [t.id, new Set()]));
    for (const r of relations) {
      if (r.sourceTable !== r.targetTable && deps.has(r.sourceTable) && deps.has(r.targetTable)) {
        deps.get(r.targetTable).add(r.sourceTable);
      }
    }
    const ordered = [];
    const placed = new Set();
    const pending = tables.slice();
    while (pending.length) {
      let i = pending.findIndex((t) => [...deps.get(t.id)].every((d) => placed.has(d)));
      if (i < 0) i = 0; // ciclo: se rompe con ALTER TABLE más abajo
      const [t] = pending.splice(i, 1);
      ordered.push(t);
      placed.add(t.id);
    }

    const emitted = new Set();
    const deferred = [];
    const blocks = [];
    for (const t of ordered) {
      const pks = t.fields.filter((f) => f.pk);
      const lines = t.fields.map((f) => columnSQL(f, pks.length === 1));
      if (pks.length > 1) lines.push(`  PRIMARY KEY (${pks.map((f) => q(f.name)).join(', ')})`);
      for (const r of relations) {
        if (r.targetTable !== t.id) continue;
        const fk = fkSQL(r);
        if (!fk) continue;
        // SQLite no soporta ADD CONSTRAINT y no exige que la tabla referenciada exista aún.
        if (dialect === 'sqlite' || r.sourceTable === t.id || emitted.has(r.sourceTable)) lines.push('  ' + fk);
        else deferred.push(`ALTER TABLE ${q(t.name)}\n  ADD ${fk};`);
      }
      emitted.add(t.id);
      blocks.push(
        (t.junction ? '-- Tabla puente (relación N:M)\n' : '') +
          `CREATE TABLE ${q(t.name)} (\n${lines.join(',\n')}\n);`
      );
    }

    const header = dialect === 'sqlite' && relations.length ? 'PRAGMA foreign_keys = ON;\n\n' : '';
    const tail = deferred.length ? '\n\n' + deferred.join('\n\n') : '';
    return header + blocks.join('\n\n') + tail + '\n';
  }

  return { generateSQL };
});
